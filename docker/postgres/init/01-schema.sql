-- Mirror of the updater's Postgres schema. The updater owns the schema (D3); this
-- file only exists so `ddl-auto=validate` passes against this repo's own dev DB.
--
-- Generated (not hand-written) from the updater's JPA entities with Hibernate
-- 7.4.5 + PostgreSQLDialect, i.e. exactly what the updater's `ddl-auto=update`
-- creates. Regenerate when the updater's entities change. Once the updater has
-- Flyway (X1), reuse its migrations instead.
--
-- Note: example_sentence text columns are `oid` (large objects) because the
-- updater maps them with @Lob. See cross-repo task X7.

create table example_sentence (
    id bigint not null,
    english oid,
    index_words oid,
    japanese oid not null,
    source varchar(255),
    primary key (id)
);

create table kanji (
    character varchar(255) not null,
    classical_radical integer,
    codepoint varchar(255),
    frequency integer,
    grade integer,
    jlpt integer,
    joyo boolean,
    kunyomi varchar(255) array,
    meanings varchar(255) array,
    nanori varchar(255) array,
    onyomi varchar(255) array,
    stroke_count integer,
    stroke_paths varchar(255) array,
    primary key (character)
);

create table kanji_radical (
    kanji varchar(255) not null,
    radical varchar(255) not null,
    primary key (kanji, radical)
);

create table name_entry (
    ent_seq bigint not null,
    kanji varchar(255) array,
    name_types varchar(255) array,
    readings varchar(255) array,
    translations varchar(255) array,
    primary key (ent_seq)
);

create table radical (
    character varchar(255) not null,
    stroke_count integer,
    primary key (character)
);

create table reading (
    id bigint generated by default as identity,
    kanji boolean,
    text varchar(255) not null,
    ent_seq bigint,
    primary key (id)
);

create table sense (
    id bigint generated by default as identity,
    ent_seq bigint,
    primary key (id)
);

create table sense_gloss (
    sense_id bigint not null,
    gloss varchar(255)
);

create table sense_misc (
    sense_id bigint not null,
    misc varchar(255)
);

create table sense_pos (
    sense_id bigint not null,
    pos varchar(255)
);

create table source_version (
    feed_id varchar(255) not null,
    content_hash varchar(255),
    last_checked_at timestamp(6) with time zone,
    last_updated_at timestamp(6) with time zone,
    primary key (feed_id)
);

create table vocab_entry (
    ent_seq bigint not null,
    common boolean,
    primary key (ent_seq)
);

